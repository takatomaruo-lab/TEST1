export const DEFAULT_MODE_ID = 'propose';

export function getMode(id) {
  return AI_MODES.find((m) => m.id === id) || AI_MODES.find((m) => m.id === DEFAULT_MODE_ID);
}

export function getModeLabel(id) {
  const m = AI_MODES.find((x) => x.id === id);
  return m ? m.label : '';
}

// サーバー側で組み立てるシステムプロンプト全文
export function buildSystemInstruction(id) {
  return `${BASE_INSTRUCTION}\n\n${getMode(id).system}`;
}